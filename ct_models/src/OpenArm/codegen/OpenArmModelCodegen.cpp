/*!
 * Code generator for the OpenArm v1 bimanual model (run once, and again when the URDF changes).
 *
 * For each arm, Pinocchio evaluates the joint-space model with the CppADCodeGen scalar
 * (OpenArmPinocchioModel.cpp) and ct::core::DerivativesCppadCG writes plain C++ into
 * include/ct/models/OpenArm/codegen:
 *   OpenArmRightModel / OpenArmLeftModel   input x = [q; dq] (7 + 7), output [M (49); C (49); G (7)], row-major
 *   OpenArmJointLimits.h                   URDF position limits, in urdfJointNames() order
 * The generated code needs Eigen and ct_core only; Pinocchio is not needed to use the model.
 */

#include "OpenArmPinocchioModel.h"

#include <ct/core/core.h>
#include <ct/models/CodegenOutputDirs.h>

#include <fstream>
#include <iomanip>
#include <iostream>

using namespace ct::models::OpenArm::codegen;

typedef ct::core::DerivativesCppadCG<IN_DIM, OUT_DIM> ModelCodegen;

void writeJointLimits(const std::string& outputDir)
{
    std::ofstream out(outputDir + "/OpenArmJointLimits.h");
    out << "// Generated by ct_models OpenArmModelCodegen from the official OpenArm URDF. Do not edit.\n"
        << "#pragma once\n\n#include <Eigen/Core>\n\nnamespace ct {\nnamespace models {\nnamespace OpenArm {\n\n"
        << std::setprecision(17);
    for (const bool upper : {false, true})
    {
        const std::string name = upper ? "jointUpperLimit" : "jointLowerLimit";
        out << "//! URDF position " << (upper ? "upper" : "lower") << " limits [rad], urdfJointNames() order\n"
            << "template <typename SCALAR = double>\nconst Eigen::Matrix<SCALAR, 14, 1>& " << name << "()\n{\n"
            << "    static Eigen::Matrix<SCALAR, 14, 1> " << name << ";\n    " << name << " << ";
        bool first = true;
        for (const std::string arm : {"left", "right"})
            for (const double v : positionLimits(arm, upper))
            {
                out << (first ? "" : ", ") << v;
                first = false;
            }
        out << ";\n    return " << name << ";\n}\n\n";
    }
    out << "}  // namespace OpenArm\n}  // namespace models\n}  // namespace ct\n";
}

int main(int argc, char** argv)
{
    loadUrdf(OPENARM_URDF_PATH);
    const std::string outputDir = ct::models::OPENARM_CODEGEN_OUTPUT_DIR;

    for (const std::string arm : {"right", "left"})
    {
        typename ModelCodegen::FUN_TYPE_CG f = [arm](const typename ModelCodegen::IN_TYPE_CG& x) {
            const std::vector<ADCGScalar> in(x.data(), x.data() + IN_DIM);
            const std::vector<ADCGScalar> out = modelTerms(arm, in);
            typename ModelCodegen::OUT_TYPE_CG y;
            for (size_t k = 0; k < OUT_DIM; ++k)
                y(k) = out[k];
            return y;
        };
        ModelCodegen generator(f);
        const std::string name = std::string("OpenArm") + (arm == "right" ? "Right" : "Left") + "Model";
        std::cout << "Generating " << name << " ..." << std::endl;
        generator.generateForwardZeroSource(name, outputDir, ct::core::CODEGEN_TEMPLATE_DIR, "models", "OpenArm");
    }
    writeJointLimits(outputDir);
    std::cout << "... done! Output in " << outputDir << std::endl;
    return 0;
}
